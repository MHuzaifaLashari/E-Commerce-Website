"""Pull the product-page details (Description / Features / Comparables) from citadelbrands.com for
every style in assets/js/products.js and write assets/js/product-details.js.

Usage (from the site folder):  python tools/citadel_details.py
Per style it reads: heading, "Model Wearing", Fabrication & Construction bullets, case quantity,
document links (Print Guide / Color Chart / Product Sheet), the Features table, sizes and the
Comparables list. Prices are not imported."""
import re, json, html, time, urllib.request
from concurrent.futures import ThreadPoolExecutor

UA = {'User-Agent': 'Mozilla/5.0'}
codes = re.findall(r'\{code:"([A-Z0-9]+)"', open('assets/js/products.js', encoding='utf-8').read())
T = lambda x: re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', x)).strip()

def get(u):
    err = None
    for _ in range(3):
        try: return urllib.request.urlopen(urllib.request.Request(u, headers=UA), timeout=60).read().decode('utf-8', 'ignore')
        except Exception as e: err = e; time.sleep(2)
    raise err

def fix_case(s):
    s = s.replace('RIngspun', 'Ringspun')
    return s

def one(code):
    url = 'https://www.citadelbrands.com/product/%s/X.html' % code
    try: page = html.unescape(get(url))
    except Exception as e: return code, {'error': str(e)}
    t = re.search(r'<h2 class="prodTitle">\s*([^<]+?)\s*</h2>', page)
    if not t: return code, {'error': 'not found on citadelbrands.com'}
    out = {'url': url.replace('/X.html', '/' + re.sub(r'[^A-Za-z0-9]+', '-', re.sub(r'^%s\s*-?\s*' % code, '', t.group(1))).strip('-') + '.html')}
    d = re.search(r'<div class="prodCatalogDesc">(.*?)<div class=\'prodTopTabOuter|<div class="prodCatalogDesc">(.*?)</table>', page, re.S)
    i = page.find('<div class="prodCatalogDesc">'); j = page.find("id='prodFeatTab'")
    desc = page[i:j] if i > 0 and j > i else ''
    # heading = first bold / paragraph text
    bolds = [T(b) for b in re.findall(r'<(?:b|strong)>(.*?)</(?:b|strong)>', desc, re.S)]
    bolds = [b.replace('�', '').strip() for b in bolds if b.replace('�', '').strip()]
    plain = [b for b in bolds if not re.match(r'(?i)(model wearing|case quantity|fabrication)', b)]
    out['heading'] = next((b for b in plain if len(b) <= 60), '')
    out['intro'] = next((b for b in plain if len(b) > 60), '')
    mw = re.search(r'Model Wearing:\s*([^<]+)', desc)
    if mw: out['modelWearing'] = re.sub(r'\s*/\s*', '/', mw.group(1).replace('�', '').strip()).title()
    out['bullets'] = [fix_case(T(b)).replace('�', '').strip() for b in re.findall(r'<li>(.*?)</li>', desc, re.S) if T(b)]
    out['caseQty'] = [T(c) for c in re.findall(r'(Case Quantity[^<]*:\s*\d+)', desc)]
    docs = []
    for href, label in re.findall(r'<a[^>]+href="([^"]+\.pdf)"[^>]*>\s*([^<]+?)\s*</a>', desc):
        if href.startswith('/'): href = 'https://www.citadelbrands.com' + href
        label = label.replace('�', '').strip()
        if re.search(r'(?i)print guide', label): label = 'Print Guide'      # site typo "Coot T Print Guide"
        if label and all(d_[1] != label for d_ in docs): docs.append((href, label))
    out['docs'] = [{'label': l, 'url': u} for u, l in docs]
    # Features table: name/value rows (category rows like "Hoodies | Hoodies" are kept once)
    feat = page[j:page.find('Have a Wholesale Account', j)] if j > 0 else ''
    rows = []
    for k, v in re.findall(r'<td[^>]*>\s*([^<]+?)\s*</td>\s*<td[^>]*>\s*([^<]+?)\s*</td>', feat):
        k, v = T(k), fix_case(T(v))
        rows.append([k, v])
    out['features'] = rows
    sz = re.search(r'Sizes:(.*?)Colors:', page, re.S)
    out['sizes'] = [x.strip() for x in T(sz.group(1)).split(',') if x.strip()] if sz else []
    comps = []
    for pid, href, name in re.findall(r"<div class='compDetail[^']*' data-productid=\"([^\"]+)\">.*?<a href=\"([^\"]+)\">.*?<span>([^<]+)</span>", page, re.S):
        if pid.upper() != code and all(c['code'] != pid.upper() for c in comps):
            comps.append({'code': pid.upper(), 'name': name.strip().title(), 'url': href})
    out['comparables'] = comps
    return code, out

with ThreadPoolExecutor(6) as ex:
    res = dict(ex.map(one, codes))
js = ('/* AUTO-GENERATED by tools/citadel_details.py from citadelbrands.com product pages — do not edit by hand.\n'
      '   Description bullets, model wearing, case quantity, documents, features table, sizes, comparables. */\n'
      'window.CB_DETAILS=%s;\n' % json.dumps(res, indent=0))
open('assets/js/product-details.js', 'w', encoding='utf-8').write(js)
for c in codes:
    r = res[c]
    if 'error' in r: print('%-7s ERROR %s' % (c, r['error'])); continue
    print('%-7s bullets=%-2d case=%s docs=%s feat=%-2d sizes=%-2d comps=%-2d mw=%s | %s' % (
        c, len(r['bullets']), r['caseQty'], [d['label'] for d in r['docs']], len(r['features']), len(r['sizes']),
        len(r['comparables']), r.get('modelWearing', '-'), r['heading']))
